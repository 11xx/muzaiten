#!/usr/bin/env python3
"""Regenerate the Han reading data the search fold compiles in.

Runs ICU's `uconv` over every CJK unified ideograph and writes two files next
to the fold tables:

  han_pinyin.tsv      toneless pinyin<TAB>every ideograph ICU reads that way
  han_simplified.tsv  simplified form<TAB>every traditional form ICU maps to it

The readings are ICU's per-character defaults (Han-Latin), so polyphones take
their most common reading; word-level readings live in tables/han.json. The
data is CLDR's, distributed under the Unicode License v3 (see
src/search/fold/UNICODE-LICENSE.txt).

Usage: tools/fold-han-data.py [output-dir]   (default: src/search/fold)
"""

import pathlib
import subprocess
import sys
import unicodedata
from collections import defaultdict

IDEOGRAPH_BLOCKS = [
    (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0x20000, 0x2A6DF), (0x2A700, 0x2B73F),
    (0x2B740, 0x2B81F), (0x2B820, 0x2CEAF), (0x2CEB0, 0x2EBEF), (0x2EBF0, 0x2EE5F),
    (0x30000, 0x3134F), (0x31350, 0x323AF),
]


def uconv(transform: str, chars: list[str]) -> list[str]:
    result = subprocess.run(
        ["uconv", "-f", "utf-8", "-t", "utf-8", "-x", transform],
        input="\n".join(chars) + "\n", capture_output=True, text=True, check=True)
    lines = result.stdout.split("\n")[: len(chars)]
    if len(lines) != len(chars):
        sys.exit(f"uconv {transform}: expected {len(chars)} lines, got {len(lines)}")
    return lines


def main() -> None:
    out_dir = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "src/search/fold")
    chars = [chr(cp) for lo, hi in IDEOGRAPH_BLOCKS for cp in range(lo, hi + 1)
             if unicodedata.category(chr(cp)) == "Lo"]
    icu = subprocess.run(["uconv", "--version"], capture_output=True, text=True).stdout.strip()

    readings: dict[str, list[str]] = defaultdict(list)
    for ch, reading in zip(chars, uconv("Han-Latin; Latin-ASCII; Lower", chars)):
        reading = reading.strip()
        if reading != ch and reading.isascii() and reading.isalpha():
            readings[reading].append(ch)

    simplified: dict[str, list[str]] = defaultdict(list)
    for ch, simple in zip(chars, uconv("Traditional-Simplified", chars)):
        if simple != ch and len(simple) == 1:
            simplified[simple].append(ch)

    header = (f"# Generated by tools/fold-han-data.py from {icu}.\n"
              "# CLDR data, Unicode License v3: see UNICODE-LICENSE.txt.\n")
    with open(out_dir / "han_pinyin.tsv", "w", encoding="utf-8") as f:
        f.write(header + "# toneless pinyin<TAB>ideographs with that default reading\n")
        for reading in sorted(readings):
            f.write(f"{reading}\t{''.join(readings[reading])}\n")
    with open(out_dir / "han_simplified.tsv", "w", encoding="utf-8") as f:
        f.write(header + "# simplified<TAB>traditional forms folded onto it\n")
        for simple in sorted(simplified):
            f.write(f"{simple}\t{''.join(simplified[simple])}\n")


if __name__ == "__main__":
    main()
