    def test_unihan_pin_accepts_runtime_mismatch_and_rejects_bad_hash(self):
        with tempfile.TemporaryDirectory() as directory:
            cache = pathlib.Path(directory)
            archive = cache / f"Unihan-{checker.UNIHAN_VERSION}.zip"
            archive.write_bytes(b"verified reference")
            digest = hashlib.sha256(archive.read_bytes()).hexdigest()
            with mock.patch.object(checker, "TOOLS_CACHE", cache), \
                 mock.patch.object(checker, "UNIHAN_SHA256", digest):
                for version in ("15.0.0", "16.0.0", "17.0.0"):
                    with self.subTest(runtime=version), \
                         mock.patch.object(checker.unicodedata, "unidata_version", version):
                        self.assertEqual(checker.unihan_archive(archive), archive)
                        self.assertEqual(checker.unihan_archive(None), archive)
                archive.write_bytes(b"corrupt reference")
                for path in (archive, None):
                    with self.subTest(path=path), \
                         self.assertRaisesRegex(SystemExit, "expected Unihan 18.0.0"):
                        checker.unihan_archive(path)

