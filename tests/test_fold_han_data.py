                self.assertEqual(pinyin_rows, ["tian\t㐁", "xi\t㐂"])
                self.assertEqual([line for line in simplified.splitlines() if not line.startswith("#")],
                                 ["一\t㐁"])
                for text in (pinyin, simplified):
                    self.assertIn("from Unihan 18.0.0.", text)
                    self.assertIn("# Python Unicode data: 16.0.0.", text)
                    self.assertIn(f"# SHA-256: {checker.UNIHAN_SHA256}", text)
                    self.assertIn(f"# Source: {checker.UNIHAN_URL}", text)
                with mock.patch.object(checker.unicodedata, "unidata_version", "17.0.0"):
                    checker.generate(archive, authored, output)
                    self.assertEqual(pinyin_rows, [line for line in (output / "han_pinyin.tsv")
                                    .read_text(encoding="utf-8").splitlines() if not line.startswith("#")])
                    categories["㐃"] = "Lo"
                    categories["\U000323b0"] = "Lo"
                    checker.generate(archive, authored, output)
                self.assertIn("he\t㐃\U000323b0\n", (output / "han_pinyin.tsv").read_text(encoding="utf-8"))
                self.assertIn("一\t㐁㐃\U000323b0\n", (output / "han_simplified.tsv").read_text(encoding="utf-8"))
